import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import vm from "node:vm";

const source = await readFile("reconstructed/patched-worker.js", "utf8");
const pnlStart = source.indexOf("function paperTradePnl(");
const pnlEnd = source.indexOf("\nfunction updateProfitProtectionState", pnlStart);
const summaryStart = source.indexOf("async function getPaperSummary(");
const summaryEnd = source.indexOf("\nfunction setupMessage", summaryStart);
assert.ok(pnlStart >= 0 && pnlEnd > pnlStart && summaryStart >= 0 && summaryEnd > summaryStart);
const context = vm.createContext({ PAPER_ACCOUNT_KEY:"paper", PAPER_STARTING_BALANCE_MON:100, MAX_AGE:120000 });
vm.runInContext(source.slice(pnlStart,pnlEnd) + "\n" + source.slice(summaryStart,summaryEnd) + "\nglobalThis.feeTests={paperTradePnl,getPaperSummary};",context);
const trade={side:"LONG",entryPrice:100,entryMonUsd:0.2,marginMon:22,leverage:50};
const stop=context.paperTradePnl(trade,99.6,0.2);
assert.ok(Math.abs(stop.grossMon-(-4.4))<1e-9);
assert.ok(Math.abs(stop.feeMon-0.65868)<1e-9);
assert.ok(Math.abs(stop.netMon-(-5.05868))<1e-9);
const flat=context.paperTradePnl(trade,100,0.2);
assert.ok(flat.netMon<0,"flat-price trades must be losses after round-trip fees");
const now=1800000000000;
const state={startingBalanceMon:100,availableBalanceMon:95.6,realizedPnlMon:-4.4,realizedPnlUsd:-0.88,wins:0,losses:1,breakeven:0,closedCount:1,trades:[{...trade,status:"CLOSED",exitPrice:99.6,exitMonUsd:0.2,grossPnlMon:-4.4,grossPnlUsd:-0.88,closedAtMs:now,mode:"TREND_HOLD",feeModelVersion:"LEVERUP_TAKER_2_85BPS_EACH_SIDE_V1",feeMon:0.625746,netPnlMon:-5.025746}]};
const storage={async get(){return state;},async put(_key,value){Object.assign(state,value);}};
const summary=await context.feeTests.getPaperSummary(storage,{MON:0.2},now,now-1000);
assert.ok(Math.abs(summary.realizedPnlMon-(-5.05868))<1e-9);
assert.ok(Math.abs(summary.availableBalanceMon-94.94132)<1e-9);
assert.ok(Math.abs(summary.totalPnlMon-(-5.05868))<1e-9);
assert.ok(Math.abs(summary.equityMon-94.94132)<1e-9);
assert.equal(summary.wins,0);
assert.equal(summary.losses,1);
assert.equal(summary.feeDataUnavailableCount,0);
assert.equal(state.trades[0].feeModelVersion,"LEVERUP_TAKER_3BPS_EACH_SIDE_V1");
assert.ok(source.includes("feeAwareProfit.mon >= 0.15"));
assert.ok(source.includes("Estimated 3 bps-per-side trading fees are deducted"));
const missingBasisState={startingBalanceMon:100,availableBalanceMon:100,realizedPnlMon:0,realizedPnlUsd:0,wins:0,losses:0,breakeven:0,closedCount:1,trades:[{side:"LONG",entryPrice:100,marginMon:10,leverage:50,status:"CLOSED",exitPrice:101,exitMonUsd:0.2,grossPnlMon:5,grossPnlUsd:1,closedAtMs:now}]};
const missingBasisStorage={async get(){return missingBasisState;},async put(_key,value){Object.assign(missingBasisState,value);}};
const missingBasisSummary=await context.feeTests.getPaperSummary(missingBasisStorage,{MON:0.2},now,now-1000);
assert.equal(missingBasisSummary.feeDataUnavailableCount,1);
assert.equal(missingBasisState.trades[0].feeModelVersion,"LEGACY_FEE_DATA_UNAVAILABLE");
console.log("Paper fee accounting and historical migration tests passed.");
